SEO_FIELDS = ('article', 'faqs', 'seo_title', 'seo_description')


def fill_seo_content(product) -> bool:
    """Fill the product's empty SEO fields from SEO_CONTENT. Never overwrites text an admin has written."""
    content = SEO_CONTENT.get(product.slug)
    if not content:
        return False
    changed = [f for f in SEO_FIELDS if not getattr(product, f) and content.get(f)]
    for f in changed:
        setattr(product, f, content[f])
    if changed:
        product.save(update_fields=changed)
    return bool(changed)
